/**
 * Image Suite — Professional CNC & Laser G-Code Post-Processor
 * Generates industry-standard G-Code (GRBL, Marlin, LinuxCNC, Mach3/4) with dynamic spindle/laser modulation.
 */

import type { ToolpathSimulationResult } from './toolpath-generator';

export interface GCodeExportConfig {
  flavor: 'grbl-laser' | 'grbl-cnc' | 'marlin' | 'linuxcnc';
  commentHeader: boolean;
  safeZ: number;       // Safe retract height (mm)
  spindleSpeed: number; // RPM or Laser Max S-value (e.g. 1000 or 18000)
}

export const DEFAULT_GCODE_CONFIG: GCodeExportConfig = {
  flavor: 'grbl-laser',
  commentHeader: true,
  safeZ: 5.0,
  spindleSpeed: 1000,
};

/**
 * Generates full formatted G-Code file content from toolpaths
 */
export function generateGCode(
  simulation: ToolpathSimulationResult,
  config: GCodeExportConfig = DEFAULT_GCODE_CONFIG
): string {
  const lines: string[] = [];

  // Header & Job Metadata
  if (config.commentHeader) {
    lines.push('; ===================================================');
    lines.push('; Generated by Image Suite CNC / Laser CAM Workstation');
    lines.push(`; Machine Flavor: ${config.flavor.toUpperCase()}`);
    lines.push(`; Total Operations: ${simulation.operations.length}`);
    lines.push(`; Total Cut Distance: ${simulation.totalCutLengthMm.toFixed(1)} mm`);
    lines.push(`; Total Rapid Distance: ${simulation.totalRapidLengthMm.toFixed(1)} mm`);
    lines.push(`; Estimated Run Time: ${Math.ceil(simulation.totalEstimatedTimeSec / 60)} min`);
    lines.push('; ===================================================');
    lines.push('');
  }

  // Machine Initialization
  lines.push('G21 ; Set units to millimeters');
  lines.push('G90 ; Absolute coordinates');
  lines.push('G17 ; XY Plane selection');
  lines.push('G94 ; Feedrate mode (units per minute)');

  if (config.flavor === 'grbl-laser') {
    lines.push('M5 ; Ensure laser is OFF');
  } else {
    lines.push(`G0 Z${config.safeZ.toFixed(2)} ; Move to safe clearance`);
    lines.push(`M3 S${config.spindleSpeed} ; Spindle ON`);
    lines.push('G4 P2 ; Dwell 2 seconds for spindle spin-up');
  }

  lines.push('');

  // Process Each CAM Operation
  simulation.operations.forEach((op, opIndex) => {
    lines.push(`; --- Operation ${opIndex + 1}: ${op.opName} ---`);

    for (const seg of op.segments) {
      if (seg.type === 'rapid') {
        if (config.flavor === 'grbl-laser') {
          lines.push('M5 ; Laser OFF for rapid move');
          lines.push(`G0 X${seg.to.x.toFixed(3)} Y${seg.to.y.toFixed(3)} F${seg.feedRateMmMin}`);
        } else {
          lines.push(`G0 X${seg.to.x.toFixed(3)} Y${seg.to.y.toFixed(3)} Z${seg.to.z.toFixed(3)} F${seg.feedRateMmMin}`);
        }
      } else if (seg.type === 'plunge') {
        lines.push(`G1 Z${seg.to.z.toFixed(3)} F${seg.feedRateMmMin}`);
      } else if (seg.type === 'cut') {
        if (config.flavor === 'grbl-laser') {
          const powerS = Math.round(((seg.powerPercent || 100) / 100) * config.spindleSpeed);
          lines.push(`M4 S${powerS} ; Dynamic Laser Power`);
          lines.push(`G1 X${seg.to.x.toFixed(3)} Y${seg.to.y.toFixed(3)} F${seg.feedRateMmMin}`);
        } else {
          lines.push(`G1 X${seg.to.x.toFixed(3)} Y${seg.to.y.toFixed(3)} Z${seg.to.z.toFixed(3)} F${seg.feedRateMmMin}`);
        }
      } else if (seg.type === 'retract') {
        lines.push(`G0 Z${seg.to.z.toFixed(3)} F${seg.feedRateMmMin}`);
      }
    }

    lines.push('');
  });

  // End of Job Footer
  lines.push('; --- End of Job ---');
  if (config.flavor === 'grbl-laser') {
    lines.push('M5 ; Laser OFF');
  } else {
    lines.push('M5 ; Spindle OFF');
    lines.push(`G0 Z${config.safeZ.toFixed(2)} ; Retract to safe Z`);
  }
  lines.push('G0 X0.000 Y0.000 ; Return to origin');
  lines.push('M2 ; Program End');

  return lines.join('\n');
}
